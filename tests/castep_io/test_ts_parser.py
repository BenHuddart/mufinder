from __future__ import annotations

from pathlib import Path

import pytest

from mufinder.castep_io import parse_transition_state_file
from mufinder.castep_io.ts_parser import TransitionStateParseError, parse_transition_state_text

_FIXTURES = Path(__file__).parents[1] / "fixtures"
_FIXTURE = _FIXTURES / "transition_state_path.ts"
_NEB_FIXTURE = _FIXTURES / "neb_path.ts"


def test_parse_transition_state_file_returns_final_path() -> None:
    parsed = parse_transition_state_file(_FIXTURE)

    assert len(parsed.images) >= 2
    assert parsed.images[0].label == "REA"
    assert parsed.images[-1].label == "PRO"
    assert parsed.barrier_height_eV is not None


def test_parse_neb_path_selects_final_iteration_band() -> None:
    # Synthetic multi-iteration NEB band: REA + 5 TST images x 3 iterations + PRO,
    # generated by tests/fixtures/generate_neb_ts.py with an encoded 0.12 eV barrier.
    parsed = parse_transition_state_file(_NEB_FIXTURE)

    # Only the converged (final-iteration) band is returned, ordered by coordinate.
    assert [image.label for image in parsed.images] == ["REA", "TST", "TST", "TST", "TST", "TST", "PRO"]
    assert parsed.images[0].reaction_coordinate == pytest.approx(0.0)
    assert parsed.images[-1].reaction_coordinate == pytest.approx(1.0)
    # All TST images come from a single (the last) NEB iteration.
    tst_iterations = {image.iteration for image in parsed.images if image.label == "TST"}
    assert len(tst_iterations) == 1

    # Energies are exposed in eV; the encoded barrier is ~0.12 eV (peak at the midpoint).
    assert parsed.barrier_height_eV == pytest.approx(0.12, abs=2e-3)
    peak = max(parsed.images, key=lambda image: image.energy)
    assert peak.reaction_coordinate == pytest.approx(0.5)


def test_parse_lstqst_output_is_rejected() -> None:
    # LST/QST output (only `LST`/`PRO` tags, no `REA`/`TST`) is not a NEB path and
    # must raise rather than silently returning a bogus path.
    lst_text = "\n".join(
        [
            " LST    0      0.00000000E+000",
            "              -6.67206998E+003     -6.67206998E+003                       <-- E",
            "               2.05295802E+001      0.00000000E+000      0.00000000E+000  <-- h",
            "               0.00000000E+000      2.05295802E+001      0.00000000E+000  <-- h",
            "               0.00000000E+000      0.00000000E+000      2.05295802E+001  <-- h",
            " H:mu        1      1.00000000E+000      1.00000000E+000      1.00000000E+000  <-- R",
            " H:mu        1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- F",
            "  ",
        ]
    )
    with pytest.raises(TransitionStateParseError):
        parse_transition_state_text(lst_text)
