"""Tests for CASTEP transition-state (``.ts``) path parsing."""

from __future__ import annotations

from dataclasses import FrozenInstanceError
from pathlib import Path

import pytest
from ase.units import Bohr, Hartree

from mufinder.castep_io import parse_transition_state_file
from mufinder.castep_io.ts_parser import (
    TransitionStateImage,
    TransitionStateParseError,
    TransitionStatePath,
    parse_transition_state_text,
)

_FIXTURES = Path(__file__).parents[1] / "fixtures"
_FIXTURE = _FIXTURES / "transition_state_path.ts"
_NEB_FIXTURE = _FIXTURES / "neb_path.ts"

# A minimal, well-formed single image block (2 atoms). Reused to assemble paths.
_IMAGE_BODY = (
    "              -1.00000000E+000     -1.00000000E+000                       <-- E\n"
    "               7.00000000E+000      0.00000000E+000      0.00000000E+000  <-- h\n"
    "               0.00000000E+000      7.00000000E+000      0.00000000E+000  <-- h\n"
    "               0.00000000E+000      0.00000000E+000      7.00000000E+000  <-- h\n"
    " H           1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- R\n"
    " H           2      0.00000000E+000      0.00000000E+000      1.00000000E+000  <-- R\n"
    " H           1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- F\n"
    " H           2      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- F\n"
)


def _block(header: str, body: str = _IMAGE_BODY) -> str:
    return header + "\n" + body


def _full_path_text(extra: str = "") -> str:
    return (
        " TSTYPE TSConfirmation\n"
        + _block(" REA    1      0.00000000E+000")
        + extra
        + _block(" PRO    1      1.00000000E+000")
    )


# --- Complete paths -----------------------------------------------------------


def test_parse_transition_state_file_returns_final_path() -> None:
    parsed = parse_transition_state_file(_FIXTURE)

    assert len(parsed.images) >= 2
    assert parsed.images[0].label == "REA"
    assert parsed.images[-1].label == "PRO"
    assert parsed.barrier_height_eV is not None


def test_parse_neb_path_selects_final_iteration_band() -> None:
    # Synthetic multi-iteration NEB band: REA + 5 TST images x 3 iterations + PRO,
    # generated by tests/fixtures/generate_neb_ts.py with an encoded 0.12 eV barrier.
    parsed = parse_transition_state_file(_NEB_FIXTURE)

    # Only the converged (final-iteration) band is returned, ordered by coordinate.
    assert [image.label for image in parsed.images] == ["REA", "TST", "TST", "TST", "TST", "TST", "PRO"]
    assert parsed.images[0].reaction_coordinate == pytest.approx(0.0)
    assert parsed.images[-1].reaction_coordinate == pytest.approx(1.0)
    # All TST images come from a single (the last) NEB iteration.
    tst_iterations = {image.iteration for image in parsed.images if image.label == "TST"}
    assert len(tst_iterations) == 1

    # Energies are exposed in eV; the encoded barrier is ~0.12 eV (peak at the midpoint).
    assert parsed.barrier_height_eV == pytest.approx(0.12, abs=2e-3)
    peak = max(parsed.images, key=lambda image: image.energy)
    assert peak.reaction_coordinate == pytest.approx(0.5)


def test_parse_neb_path_converts_geometry_from_bohr_to_angstrom() -> None:
    # The fixture stores an fcc Cu cell with a = 6.8431966 Bohr; the parser must
    # expose lattice vectors and positions in Å (~3.6213 Å), not raw Bohr.
    parsed = parse_transition_state_file(_NEB_FIXTURE)

    reactant = parsed.images[0]
    assert reactant.lattice_vectors[0] == pytest.approx((3.6213, 0.0, 0.0), abs=1e-4)
    assert reactant.lattice_vectors[1] == pytest.approx((0.0, 3.6213, 0.0), abs=1e-4)
    assert reactant.lattice_vectors[2] == pytest.approx((0.0, 0.0, 3.6213), abs=1e-4)
    assert reactant.species == ("Cu", "Cu", "Cu", "Cu", "H:mu")
    # Second Cu atom sits at (a/2, a/2, 0); the muon starts at the octahedral site (a/2, a/2, a/2).
    assert reactant.cartesian_positions[1] == pytest.approx((1.81063, 1.81063, 0.0), abs=1e-4)
    assert reactant.cartesian_positions[4] == pytest.approx((1.81063, 1.81063, 1.81063), abs=1e-4)
    # The product image moves the muon to the tetrahedral site at (a/4, a/4, a/4).
    product = parsed.images[-1]
    assert product.cartesian_positions[4] == pytest.approx((0.90532, 0.90532, 0.90532), abs=1e-4)
    # Every image in the band shares the (fixed-cell) lattice.
    for image in parsed.images:
        for vector, expected in zip(image.lattice_vectors, reactant.lattice_vectors, strict=True):
            assert vector == pytest.approx(expected)


def test_parse_converts_lattice_positions_and_forces_to_ev_angstrom_units() -> None:
    # One image written in CASTEP atomic units: a 7 Bohr cubic cell, an atom at
    # 1 Bohr along z and a force of 0.5 Hartree/Bohr on it.
    body = (
        "              -1.00000000E+000     -1.00000000E+000                       <-- E\n"
        "               7.00000000E+000      0.00000000E+000      0.00000000E+000  <-- h\n"
        "               0.00000000E+000      7.00000000E+000      0.00000000E+000  <-- h\n"
        "               0.00000000E+000      0.00000000E+000      7.00000000E+000  <-- h\n"
        " H           1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- R\n"
        " H           2      0.00000000E+000      0.00000000E+000      1.00000000E+000  <-- R\n"
        " H           1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- F\n"
        " H           2      0.00000000E+000      0.00000000E+000      5.00000000E-001  <-- F\n"
    )
    text = " TSTYPE\n" + _block(" REA    1      0.0", body) + _block(" PRO    1      1.0", body)
    parsed = parse_transition_state_text(text)

    image = parsed.images[0]
    assert image.energy == pytest.approx(-Hartree)
    assert image.lattice_vectors[0] == pytest.approx((7.0 * Bohr, 0.0, 0.0))
    assert image.lattice_vectors[0][0] == pytest.approx(3.7042, abs=1e-4)
    assert image.cartesian_positions[1] == pytest.approx((0.0, 0.0, Bohr))
    assert image.forces[0] == pytest.approx((0.0, 0.0, 0.0))
    assert image.forces[1] == pytest.approx((0.0, 0.0, 0.5 * Hartree / Bohr))
    assert image.forces[1][2] == pytest.approx(25.711, abs=1e-3)


@pytest.mark.parametrize("as_type", [Path, str])
def test_parse_transition_state_file_reads_from_disk(tmp_path: Path, as_type: type) -> None:
    ts_file = tmp_path / "path.ts"
    ts_file.write_text(_full_path_text(), encoding="utf-8")

    parsed = parse_transition_state_file(as_type(ts_file))

    assert isinstance(parsed, TransitionStatePath)
    assert [image.label for image in parsed.images] == ["REA", "PRO"]


def test_path_with_transition_selects_latest_iteration() -> None:
    # Two TST images at different iterations; only the latest must survive.
    tst_old = _block(" TST    1      0.50000000E+000")
    tst_new = _block(" TST    2      0.50000000E+000")
    text = _full_path_text(extra=tst_old + tst_new)
    parsed = parse_transition_state_text(text)

    labels = [img.label for img in parsed.images]
    assert labels.count("TST") == 1
    tst_image = next(img for img in parsed.images if img.label == "TST")
    assert tst_image.iteration == 2
    assert labels[0] == "REA"
    assert labels[-1] == "PRO"
    # sorted by reaction coordinate: 0.0 (REA), 0.5 (TST), 1.0 (PRO)
    coords = [img.reaction_coordinate for img in parsed.images]
    assert coords == sorted(coords)


def test_unrecognized_data_line_inside_block_is_skipped() -> None:
    # A non-empty line inside a block that matches none of the "<-- *" markers
    # is ignored.
    body = (
        "              -1.0                                 <-- E\n"
        " some stray annotation line that is not a marker\n"
        "               7.0  0.0  0.0                       <-- h\n"
        "               0.0  7.0  0.0                       <-- h\n"
        "               0.0  0.0  7.0                       <-- h\n"
        " H 1 0.0 0.0 0.0                                   <-- R\n"
        " H 1 0.0 0.0 0.0                                   <-- F\n"
    )
    text = " TSTYPE\n" + _block(" REA    1      0.0", body) + _block(" PRO    1      1.0")
    parsed = parse_transition_state_text(text)
    assert len(parsed.images) == 2


# --- Barrier height and image records -----------------------------------------


def test_barrier_height_none_for_empty_path() -> None:
    empty = TransitionStatePath(images=())
    assert empty.barrier_height_eV is None


def test_barrier_height_computed_from_max_minus_first() -> None:
    parsed = parse_transition_state_text(_full_path_text())
    energies = [img.energy for img in parsed.images]
    assert parsed.barrier_height_eV == pytest.approx(max(energies) - energies[0])


def test_image_is_frozen_dataclass() -> None:
    parsed = parse_transition_state_text(_full_path_text())
    image = parsed.images[0]
    assert isinstance(image, TransitionStateImage)
    with pytest.raises(FrozenInstanceError):
        image.energy = 0.0  # type: ignore[misc]


# --- Incomplete or unrecognised paths -----------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        pytest.param("", id="empty"),
        pytest.param(" TSTYPE TSConfirmation\n random noise here\n more stuff\n", id="noise-only"),
        # "REA 1" has only 2 parts and the second header has 5, so both are skipped.
        pytest.param("REA 1\nREA junk extra here now\n", id="wrong-part-count"),
        pytest.param("REA notanint 0.0\n", id="non-numeric-iteration"),
        pytest.param("FOO 1 0.0\n", id="unknown-label"),
        pytest.param(" TSTYPE\n" + _block(" REA    1      0.0"), id="missing-products"),
    ],
)
def test_text_without_a_reactant_to_product_path_is_rejected(text: str) -> None:
    with pytest.raises(TransitionStateParseError, match="No complete transition-state path"):
        parse_transition_state_text(text)


def test_parse_lstqst_output_is_rejected() -> None:
    # LST/QST output (only `LST`/`PRO` tags, no `REA`/`TST`) is not a NEB path and
    # must raise rather than silently returning a bogus path.
    lst_text = "\n".join(
        [
            " LST    0      0.00000000E+000",
            "              -6.67206998E+003     -6.67206998E+003                       <-- E",
            "               2.05295802E+001      0.00000000E+000      0.00000000E+000  <-- h",
            "               0.00000000E+000      2.05295802E+001      0.00000000E+000  <-- h",
            "               0.00000000E+000      0.00000000E+000      2.05295802E+001  <-- h",
            " H:mu        1      1.00000000E+000      1.00000000E+000      1.00000000E+000  <-- R",
            " H:mu        1      0.00000000E+000      0.00000000E+000      0.00000000E+000  <-- F",
            "  ",
        ]
    )
    with pytest.raises(TransitionStateParseError):
        parse_transition_state_text(lst_text)


# --- Malformed image entries --------------------------------------------------


def test_invalid_energy_entry_raises() -> None:
    body = "              not_a_number                       <-- E\n"
    text = " TSTYPE\n" + _block(" REA    1      0.0", body)
    with pytest.raises(TransitionStateParseError, match="Invalid energy entry"):
        parse_transition_state_text(text)


def test_invalid_lattice_entry_too_few_values_raises() -> None:
    # The guard counts every whitespace token including the "<-- h" marker, so a
    # bare marker line (2 tokens) is the way to trip len(values) < 3.
    body = (
        "              -1.00000000E+000                       <-- E\n"
        "  <-- h\n"
    )
    text = " TSTYPE\n" + _block(" REA    1      0.0", body)
    with pytest.raises(TransitionStateParseError, match="Invalid lattice-vector entry"):
        parse_transition_state_text(text)


def test_invalid_position_entry_too_few_values_raises() -> None:
    # "X Y <-- R" -> 4 tokens (< 5) trips the position guard.
    body = (
        "              -1.00000000E+000                       <-- E\n"
        "               7.0  0.0  0.0                       <-- h\n"
        "               0.0  7.0  0.0                       <-- h\n"
        "               0.0  0.0  7.0                       <-- h\n"
        " H 1                                               <-- R\n"
    )
    text = " TSTYPE\n" + _block(" REA    1      0.0", body)
    with pytest.raises(TransitionStateParseError, match="Invalid position entry"):
        parse_transition_state_text(text)


def test_invalid_force_entry_too_few_values_raises() -> None:
    # "H 1 <-- F" -> 4 tokens (< 5) trips the force guard.
    body = (
        "              -1.00000000E+000                       <-- E\n"
        "               7.0  0.0  0.0                       <-- h\n"
        "               0.0  7.0  0.0                       <-- h\n"
        "               0.0  0.0  7.0                       <-- h\n"
        " H 1 0.0 0.0 0.0                                   <-- R\n"
        " H 1                                               <-- F\n"
    )
    text = " TSTYPE\n" + _block(" REA    1      0.0", body)
    with pytest.raises(TransitionStateParseError, match="Invalid force entry"):
        parse_transition_state_text(text)


